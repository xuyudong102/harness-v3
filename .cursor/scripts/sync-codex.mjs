export function agentsConfig() {
  return agentsConfigText(ownership);
}

export function legacyAgentsConfig() {
  return agentsConfigText(legacyOwnership, false);
}

export function validateIndexTargets(text) {
  const targets = [...text.matchAll(/(?:repo-local:\s*|Canonical source \(repo-local\):\s*)`([^`]+)`/g)].map((match) => match[1]);
  if (!targets.length) throw new Error('No declared repo-local index targets');
  for (const target of targets) {
    const file = path.resolve(root, '.cursor', target), base = fs.realpathSync(path.join(root, '.cursor'));
    if (!fs.existsSync(file)) throw new Error('MCP_RESOURCE_MISSING / missing repo-local index target: ' + target);
    const real = fs.realpathSync(file);
    if (real !== base && !real.startsWith(base + path.sep)) throw new Error('Escaping repo-local index target: ' + target);
  }
  if (!text.includes('MCP_EXTERNAL_CONFIGURATION: project-managed / host-managed')) throw new Error('Missing explicit MCP discovery mode');
  return {repoLocalTargets:targets.length, brokenIndexTargets:0, mcpMode:'MCP_EXTERNAL_CONFIGURATION', configuration:'project-managed / host-managed', runtimeConfigurationValidated:false};
}

function resolvedLink(link) {
  return path.resolve(path.dirname(link), fs.readlinkSync(link));
}

function wrapperEntries(generated) {
  return fs.existsSync(generated) ? fs.readdirSync(generated, {withFileTypes:true})
    .filter((entry) => isVisibleEntryName(entry.name) && (entry.isDirectory() || entry.isSymbolicLink())) : [];
}

function validateConfig(file, expected, legacyExpected) {
  if (!fs.existsSync(file)) return;
  if (!fs.lstatSync(file).isFile()) throw new Error('Refusing user config: ' + file);
  const text = fs.readFileSync(file, 'utf8');
  const heading = path.basename(file) === 'generated-harness-index.md' ? '# Harness Resource Discovery' : '# Harness Adapter';
  const currentOwned = text.startsWith(marker + '\n' + ownership + '\n') && text.includes('\n' + heading + '\n');
  if (!currentOwned && text !== legacyExpected && text !== legacyExpected.replace('\n' + legacyOwnership, '')) {
    throw new Error('Refusing user config: ' + file);
  }
}

function discoverLegacyInstallations(skillsDir) {
  if (!fs.existsSync(skillsDir)) return [];
  const outputs = new Set();
  for (const entry of fs.readdirSync(skillsDir, {withFileTypes:true})) {
    if (!isVisibleEntryName(entry.name) || !/^zfnjjs-[a-z0-9-]+$/.test(entry.name) || !entry.isSymbolicLink()) continue;
    const link = path.join(skillsDir, entry.name), target = resolvedLink(link);
    if (path.basename(target) !== entry.name || path.basename(path.dirname(target)) !== 'skills' || path.basename(path.dirname(path.dirname(target))) !== 'generated') continue;
    const file = path.join(target, 'SKILL.md');
    if (!legacyOwned(file)) continue;
    outputs.add(path.resolve(target, '../../..'));
  }
  return [...outputs].sort();
}

function legacyMigrationPlan(skillsDir, currentOutput) {
  const wrappers = [], configs = [];
  for (const output of discoverLegacyInstallations(skillsDir)) {
    const generated = path.join(output, 'generated/skills');
    safePath(generated, output);
    for (const entry of wrapperEntries(generated).filter((item) => /^zfnjjs-[a-z0-9-]+$/.test(item.name))) {
      const dir = path.join(generated, entry.name), file = path.join(dir, 'SKILL.md'), link = path.join(skillsDir, entry.name);
      safePath(dir, generated); safePath(file, generated);
      if (entry.isSymbolicLink() || !legacyOwned(file) || fs.readdirSync(dir).some((name) => name !== 'SKILL.md')) {
        throw new Error('Refusing unproven legacy wrapper: ' + dir);
      }
      const linkStat = fs.lstatSync(link, {throwIfNoEntry:false});
      if (linkStat && (!linkStat.isSymbolicLink() || resolvedLink(link) !== dir)) throw new Error('Refusing legacy discovery entry: ' + link);
      wrappers.push({name:entry.name, dir, file, link, output});
    }
    if (output !== currentOutput) {
      const pairs = [
        ['generated-harness-index.md', legacyIndex()],
        ['AGENTS.generated.md', legacyAgentsConfig()],
      ];
      for (const [name, expected] of pairs) {
        const file = path.join(output, 'config', name);
        safePath(file, output);
        if (!fs.existsSync(file)) continue;
        if (!fs.lstatSync(file).isFile()) throw new Error('Refusing unproven legacy config: ' + file);
        const text = fs.readFileSync(file, 'utf8');
        if (text !== expected && text !== expected.replace('\n' + legacyOwnership, '')) throw new Error('Refusing unproven legacy config: ' + file);
        configs.push(file);
      }
    }
  }
  return {wrappers, configs};
}

export function sync(output, skillsDir) {
  output = path.resolve(output); skillsDir = path.resolve(skillsDir);
  if (output === root || output.startsWith(root + path.sep)) throw new Error('Output must not be the Harness repository');
  safePath(output, output); safePath(skillsDir, skillsDir);
  if (fs.lstatSync(skillsDir, {throwIfNoEntry:false})?.isSymbolicLink()) throw new Error('Refusing symlink discovery root: ' + skillsDir);
  const generated = path.join(output, 'generated/skills');
  safePath(generated, output);
  if (output === skillsDir || output.startsWith(skillsDir + path.sep) || skillsDir.startsWith(output + path.sep)) throw new Error('Output and discovery roots must not overlap');

  const current = discover(), names = new Set(current.map((skill) => skill.name));
  const managed = [];
  for (const entry of wrapperEntries(generated)) {
    const dir = path.join(generated, entry.name), file = path.join(dir, 'SKILL.md');
    safePath(dir, generated); safePath(file, generated);
    if (entry.isSymbolicLink()) throw new Error('Refusing symlink wrapper directory: ' + dir);
    if (owned(file) || legacyOwned(file)) {
      if (fs.readdirSync(dir).some((name) => name !== 'SKILL.md')) throw new Error('Refusing wrapper with unmanaged files: ' + dir);
      managed.push({name:entry.name, dir, file, link:path.join(skillsDir, entry.name), output});
    } else if (names.has(entry.name) || /^zfnjjs-[a-z0-9-]+$/.test(entry.name)) {
      throw new Error('Refusing unmanaged wrapper: ' + dir);
    }
  }

  const migration = legacyMigrationPlan(skillsDir, output);
  const removals = new Map([...managed, ...migration.wrappers].map((item) => [item.dir, item]));

  // Full preflight before any mutation: wrappers, links, configs and legacy cleanup.
  for (const item of removals.values()) {
    const linkStat = fs.lstatSync(item.link, {throwIfNoEntry:false});
    if (linkStat && (!linkStat.isSymbolicLink() || resolvedLink(item.link) !== item.dir)) throw new Error('Refusing user Skill: ' + item.link);
  }
  for (const item of current) {
    const dir = path.join(generated, item.name), link = path.join(skillsDir, item.name), file = path.join(dir, 'SKILL.md');
    const linkStat = fs.lstatSync(link, {throwIfNoEntry:false});
    if (linkStat && (!linkStat.isSymbolicLink() || resolvedLink(link) !== dir || !owned(file))) throw new Error('Refusing user Skill: ' + link);
  }
  validateConfig(path.join(output, 'config/generated-harness-index.md'), index(), legacyIndex());
  validateConfig(path.join(output, 'config/AGENTS.generated.md'), agentsConfig(), legacyAgentsConfig());
  const discovery = index(); validateIndexTargets(discovery);

  fs.mkdirSync(generated, {recursive:true});
  fs.mkdirSync(skillsDir, {recursive:true});
  fs.mkdirSync(path.join(output, 'config'), {recursive:true});

  const removedLinks = [], removedWrappers = [], removedConfigs = [];
  for (const item of removals.values()) {
    const keep = item.output === output && names.has(item.name) && owned(item.file);
    if (keep) continue;
    if (fs.lstatSync(item.link, {throwIfNoEntry:false})) { fs.unlinkSync(item.link); removedLinks.push(item.link); }
    fs.unlinkSync(item.file); fs.rmdirSync(item.dir); removedWrappers.push(item.dir);
  }
  for (const file of migration.configs) {
    fs.unlinkSync(file); removedConfigs.push(file);
  }
  for (const item of current) {
    const dir = path.join(generated, item.name), link = path.join(skillsDir, item.name);
    fs.mkdirSync(dir, {recursive:true});
    fs.writeFileSync(path.join(dir, 'SKILL.md'), wrapper(item));
    if (!fs.lstatSync(link, {throwIfNoEntry:false})) fs.symlinkSync(dir, link, 'dir');
  }
  fs.writeFileSync(path.join(output, 'config/generated-harness-index.md'), discovery);
  fs.writeFileSync(path.join(output, 'config/AGENTS.generated.md'), agentsConfig());

  return {
    output,
    skillsDir,
    wrappers:current.length,
    staleRemoved:[...removals.values()].filter((item) => !/^zfnjjs-/.test(item.name) && !names.has(item.name)).length,
    catalogChars:current.reduce((sum, skill) => sum + skill.name.length + skill.description.length, 0),
    migration:{legacyLinksRemoved:removedLinks, legacyWrappersRemoved:removedWrappers, legacyConfigsRemoved:removedConfigs},
  };
}

function printResult(result) {
  const examples = discover().map((item) => item.name).filter((name) => ['done-verify','codearts-pipeline','systematic-debug'].includes(name));
  console.log('Harness Codex adapter synced.');
  console.log('\nAdapter:\n  ' + result.output);
  console.log('\nCanonical source:\n  ' + path.join(root, '.cursor'));
  console.log('\nSkills:\n  ' + result.wrappers + ' wrappers generated\n  Discovery: ' + result.skillsDir);
  if (examples.length) console.log('\nExamples:\n  ' + examples.join('\n  '));
  console.log('\nNext:\n  cd <business-repo>\n  codex');
  console.log(JSON.stringify(result));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const value = (name) => { const index = process.argv.indexOf(name); return index < 0 ? null : process.argv[index + 1]; };
  const defaults = defaultPaths();
  printResult(sync(value('--output') || defaults.output, value('--skills-dir') || defaults.skillsDir));
}
