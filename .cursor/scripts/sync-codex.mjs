#!/usr/bin/env node
/** Small deterministic discovery/wrapper adapter, not a resource registry or runtime. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { isVisibleEntryName, walk, root } from './harness-resource-utils.mjs';

export const marker = '<!-- GENERATED by Harness sync-codex.mjs; do not edit. -->';
export const ownerId = 'zfnjjs-harness';
export const legacyOwnerId = 'zfnjjs-harness-v2';
const canonicalRoot = fs.realpathSync(root);
export const ownership = '<!-- Harness owner: ' + ownerId + '; adapter-storage: zfnjjs; generator: sync-codex.mjs; canonical: ' + canonicalRoot + ' -->';
export const legacyOwnership = '<!-- Harness owner: ' + legacyOwnerId + '; generator: sync-codex.mjs; canonical: ' + canonicalRoot + ' -->';

export function resolveCodexHome(env = process.env) {
  const home = env.CODEX_HOME || (env.HOME ? path.join(env.HOME, '.codex') : null);
  if (!home) throw new Error('CODEX_HOME or HOME is required');
  return path.resolve(home);
}

export function defaultPaths(env = process.env) {
  const codexHome = resolveCodexHome(env);
  return {
    codexHome,
    output: path.join(codexHome, 'harness/zfnjjs'),
    skillsDir: path.join(codexHome, 'skills'),
  };
}

export function safePath(file, boundary) {
  file = path.resolve(file); boundary = path.resolve(boundary);
  if (file !== boundary && !file.startsWith(boundary + path.sep)) throw new Error('Outside managed boundary: ' + file);
  let current = path.parse(file).root;
  for (const part of file.slice(current.length).split(path.sep).filter(Boolean)) {
    current = path.join(current, part);
    const stat = fs.lstatSync(current, {throwIfNoEntry:false});
    if (!stat) break;
    if (stat.isSymbolicLink()) throw new Error('Refusing symlink path chain: ' + current);
    const real = fs.realpathSync(current);
    if (current === boundary || current.startsWith(boundary + path.sep)) {
      if (real !== boundary && !real.startsWith(boundary + path.sep)) throw new Error('Realpath escape: ' + current);
    }
  }
}

function sourceDescription(text) {
  const frontmatter = text.match(/^---\n([\s\S]*?)\n---/);
  if (!frontmatter) throw new Error('Skill frontmatter is missing');
  const match = frontmatter[1].match(/^description:\s*(.*)(?:\n((?:[ \t]+.*\n?)*))?/m);
  if (!match) throw new Error('Skill description is missing');
  return (match[1].match(/^[>|]/) ? match[2] : match[1]).trim().replace(/\s+/g, ' ');
}

export function discover() {
  const skillsRoot = path.join(root, '.cursor/skills');
  return fs.readdirSync(skillsRoot, {withFileTypes:true})
    .filter((entry) => isVisibleEntryName(entry.name) && entry.isDirectory() && /^[a-z0-9-]+$/.test(entry.name))
    .map((entry) => ({name:entry.name, source:path.join(skillsRoot, entry.name, 'SKILL.md')}))
    .filter((item) => fs.lstatSync(item.source, {throwIfNoEntry:false})?.isFile())
    .sort((a, b) => a.name.localeCompare(b.name))
    .map((item) => ({...item, description:sourceDescription(fs.readFileSync(item.source, 'utf8'))}));
}

function wrapperText(item, owner) {
  return '---\nname: ' + item.name + '\ndescription: ' + JSON.stringify(item.description) + '\n---\n\n' + marker + '\n' + owner +
    '\n\nRead the current canonical Skill only when this capability applies:\n\n' +
    '`' + item.source + '`\n\nFollow its scope and authorization boundaries. Current Coding Agent chooses engineering actions. L0/L1 create no persistent task state; code changes still require Review and fresh Final Verification.\n';
}

export function wrapper(item) {
  return wrapperText(item, ownership);
}

export function legacyWrapper(item) {
  return wrapperText({...item, name:'zfnjjs-' + item.name}, legacyOwnership);
}

function descriptor(file) {
  const match = fs.readFileSync(file, 'utf8').match(/^---\nname: ([a-z0-9-]+)\ndescription: ("[^\n]*")\n---/);
  if (!match) return null;
  try { return {name:match[1], description:JSON.parse(match[2])}; } catch { return null; }
}

export function owned(file) {
  safePath(file, path.resolve(path.dirname(file), '../..'));
  if (!fs.lstatSync(file, {throwIfNoEntry:false})?.isFile()) return false;
  const item = descriptor(file);
  const name = path.basename(path.dirname(file));
  if (!item || item.name !== name || name.startsWith('zfnjjs-') || !/^[a-z0-9-]+$/.test(name)) return false;
  const source = path.join(root, '.cursor/skills', name, 'SKILL.md');
  return fs.readFileSync(file, 'utf8') === wrapper({...item, source});
}

export function legacyOwned(file) {
  safePath(file, path.resolve(path.dirname(file), '../..'));
  if (!fs.lstatSync(file, {throwIfNoEntry:false})?.isFile()) return false;
  const item = descriptor(file);
  const name = path.basename(path.dirname(file));
  if (!item || item.name !== name || !/^zfnjjs-[a-z0-9-]+$/.test(name)) return false;
  const canonicalName = name.slice('zfnjjs-'.length);
  const source = path.join(root, '.cursor/skills', canonicalName, 'SKILL.md');
  const expected = legacyWrapper({name:canonicalName, source, description:item.description});
  const text = fs.readFileSync(file, 'utf8');
  return text === expected || text === expected.replace('\n' + legacyOwnership, '');
}

function indexText(skills, owner, discoveryGuide = true) {
  const agents = fs.readdirSync(path.join(root, '.cursor/agents'), {withFileTypes:true})
    .filter((entry) => isVisibleEntryName(entry.name) && entry.isFile() && /^[a-z0-9-]+\.md$/.test(entry.name))
    .map((entry) => entry.name).sort();
  const rules = walk(path.join(root, '.cursor/rules')).filter((file) => file.endsWith('.mdc'));
  return marker + '\n' + owner + '\n\n# Harness Resource Discovery\n\nCoding Agent chooses actions. Resources are read on demand; this index does not start a workflow or load resource bodies.\n\n' +
    'Canonical source (repo-local): `' + root + '/.cursor`\n\n' +
    (discoveryGuide ? '## How to use this index\n\n' +
      '- This file is a Harness catalog, not a preload manifest. Discover → decide → read a canonical resource on demand.\n' +
      '- Skills normally use `$CODEX_HOME/skills/<skill>` for native wrapper discovery; read the canonical `SKILL.md` only when applicable.\n' +
      '- For project facts, conventions or MCP guidance, start at repo-local `rules/rules-loader.mdc`; derive project scope from the workspace and project AGENTS.md, then search only `rules/projects/<matching-project>/`, never all project directories.\n' +
      '- Open optional Agents and Playbooks only when the task needs them.\n\n' : '') +
    '## Agents\n\n' +
    agents.map((name) => '- repo-local: `agents/' + name + '`').join('\n') +
    '\n\n## Skills\n\n' + skills.map((skill) => '- repo-local: `skills/' + skill.name + '/SKILL.md`').join('\n') +
    '\n\n## Optional playbooks\n\n' + ['bugfix','refactoring','feature-delivery'].map((name) => '- repo-local: `workflows/' + name + '.yaml`').join('\n') +
    '\n\n## Rules / MCP\n\n' + rules.length + ' Rules.\n' +
    '- repo-local: `rules/rules-loader.mdc` — scenario discovery.\n' +
    '- repo-local: `rules/projects/` — repository facts.\n' +
    '- repo-local: `rules/mcp.mdc` — naming, capabilities and setup guidance.\n' +
    '- MCP_EXTERNAL_CONFIGURATION: project-managed / host-managed; business-project `.cursor/mcp.json` or host MCP settings. Not a Harness repo-local resource; configuration is never written or runtime-validated by this adapter.\n';
}

export function index() {
  return indexText(discover(), ownership);
}

export function legacyIndex() {
  return indexText(discover(), legacyOwnership, false);
}

